// Renders a HERO Card as a one-page, print-ready PDF (US Letter) that mirrors the paper card.
import PDFDocument from 'pdfkit';
import { CHECKLIST } from '../public/js/checklist.js';

const C = {
  navy: '#0B2545', navy2: '#13315C', orange: '#F2620F', ink: '#0E1726', ink2: '#3C4A5E', muted: '#6B7A90',
  line: '#E3E8EF', sunken: '#F1F4F8',
  s: '#12925A', sBg: '#E5F6EE', i: '#D93636', iBg: '#FDECEC', c: '#2F6FDB', cBg: '#E8F0FD',
};

const L = {
  en: {
    title: 'HERO Card', subtitle: 'Safety Observation Card', card: 'Card', status: { submitted: 'ALL SATISFACTORY', open: 'OPEN', closed: 'CLOSED' },
    observer: 'Observer', date: 'Date', time: 'Time', location: 'Location', craft: 'Craft', observer_id: 'Observer ID #',
    completed_by: 'Completed by', worker: 'Employee', supervisor: 'Supervisor',
    s: 'Satisfactory', i: 'Intervention needed', c: 'Corrected', legend: 'S = Satisfactory · I = Intervention needed · C = Intervention took place and was corrected',
    summary: 'Intervention Summary', done: 'What was done?', review: 'Supervisor Review', closed_by: 'Closed by', closed_on: 'Closed on', comment: 'Comment',
    na: 'Not rated items are not applicable.', generated: 'Generated by HERO Card Digital', page: 'Page',
  },
  es: {
    title: 'HERO Card', subtitle: 'Tarjeta de observación de seguridad', card: 'Tarjeta', status: { submitted: 'TODO SATISFACTORIO', open: 'ABIERTA', closed: 'CERRADA' },
    observer: 'Observador', date: 'Fecha', time: 'Hora', location: 'Ubicación', craft: 'Oficio', observer_id: 'ID de observador',
    completed_by: 'Llenada por', worker: 'Empleado', supervisor: 'Supervisor',
    s: 'Satisfactorio', i: 'Requiere intervención', c: 'Corregido', legend: 'S = Satisfactorio · I = Requiere intervención · C = Se intervino y se corrigió',
    summary: 'Resumen de la intervención', done: '¿Qué se hizo?', review: 'Revisión del supervisor', closed_by: 'Cerrada por', closed_on: 'Fecha de cierre', comment: 'Comentario',
    na: 'Los puntos sin marcar no aplican.', generated: 'Generado por HERO Card Digital', page: 'Página',
  },
};

const fmtDate = (iso, lang, month = 'short') => {
  if (!iso) return '—';
  const [y, m, d] = iso.slice(0, 10).split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(lang === 'es' ? 'es-US' : 'en-US', { month, day: 'numeric', year: 'numeric' });
};
const fmtTime = (hhmm, lang) => {
  if (!hhmm) return '—';
  const [h, m] = hhmm.split(':').map(Number);
  return new Date(2000, 0, 1, h, m).toLocaleTimeString(lang === 'es' ? 'es-US' : 'en-US', { hour: 'numeric', minute: '2-digit' });
};

/** @returns {Promise<Buffer>} */
export function cardPdf(card, lang = 'en') {
  const t = L[lang] || L.en;
  const doc = new PDFDocument({
    size: 'LETTER', margins: { top: 40, bottom: 40, left: 40, right: 40 }, bufferPages: true,
    info: { Title: `${t.title} #${card.id}`, Author: 'HERO Card Digital', Subject: t.subtitle },
  });
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));
  const done = new Promise((resolve) => doc.on('end', () => resolve(Buffer.concat(chunks))));

  const W = doc.page.width, M = 40, CW = W - M * 2;

  // ---- header band
  doc.rect(0, 0, W, 80).fill(C.navy);
  doc.rect(0, 77, W, 3).fill(C.orange);
  // shield mark
  doc.save().translate(M, 14).scale(0.1);
  doc.path('M256 92 L392 140 V252 C392 336 334 396 256 424 C178 396 120 336 120 252 V140 Z').fill(C.orange);
  doc.path('M196 262 L240 306 L322 212').lineWidth(34).lineCap('round').lineJoin('round').stroke('#FFFFFF');
  doc.restore();
  doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(24).text(t.title, M + 50, 22, { lineBreak: false });
  doc.font('Helvetica').fontSize(10).fillColor('#C9D4E5').text(t.subtitle, M + 51, 49, { lineBreak: false });
  doc.font('Helvetica-Bold').fontSize(18).fillColor('#FFFFFF').text(`${t.card} #${card.id}`, M, 20, { width: CW, align: 'right' });
  const st = t.status[card.status] || card.status;
  const stColor = card.status === 'open' ? C.i : card.status === 'closed' ? C.c : C.s;
  doc.font('Helvetica-Bold').fontSize(8.5);
  const pw = doc.widthOfString(st) + 18;
  doc.roundedRect(W - M - pw, 46, pw, 18, 9).fill(stColor);
  doc.fillColor('#FFFFFF').text(st, W - M - pw, 51, { width: pw, align: 'center' });

  // ---- meta grid (2 rows × 4)
  let y = 94;
  const meta = [
    [t.observer, card.user_name], [t.date, fmtDate(card.card_date, lang)], [t.time, fmtTime(card.card_time, lang)], [t.location, card.location],
    [t.craft, card.craft], [t.observer_id, card.observer_id], [t.completed_by, card.completed_by === 'supervisor' ? t.supervisor : t.worker], ['', ''],
  ];
  const cellW = CW / 4;
  doc.roundedRect(M, y, CW, 72, 8).fill(C.sunken);
  meta.forEach(([k, v], idx) => {
    if (!k) return;
    const cx = M + 12 + (idx % 4) * cellW, cy = y + 10 + Math.floor(idx / 4) * 32;
    doc.font('Helvetica-Bold').fontSize(7).fillColor(C.muted).text(k.toUpperCase(), cx, cy, { width: cellW - 16, characterSpacing: 0.4 });
    doc.font('Helvetica-Bold').fontSize(10).fillColor(C.ink).text(String(v ?? '—'), cx, cy + 11, { width: cellW - 16, height: 14, ellipsis: true });
  });

  // ---- counts
  y += 82;
  const counts = [['S', t.s, card.count_s, C.s, C.sBg], ['I', t.i, card.count_i, C.i, C.iBg], ['C', t.c, card.count_c, C.c, C.cBg]];
  const bw = (CW - 16) / 3;
  counts.forEach(([letter, label, n, col, bg], k) => {
    const x = M + k * (bw + 8);
    doc.roundedRect(x, y, bw, 32, 8).fill(bg);
    doc.circle(x + 18, y + 16, 9).fill(col);
    doc.font('Helvetica-Bold').fontSize(9).fillColor('#FFFFFF').text(letter, x + 9, y + 12, { width: 18, align: 'center' });
    doc.font('Helvetica-Bold').fontSize(16).fillColor(col).text(String(n), x + 34, y + 9, { lineBreak: false });
    const nw = doc.widthOfString(String(n)); // measured while the 16pt bold font is active
    doc.font('Helvetica').fontSize(8.5).fillColor(C.ink2).text(label, x + 34 + nw + 8, y + 13, { width: bw - 50 - nw, lineBreak: false });
  });

  // ---- checklist in two columns (mirrors the two sides of the paper card)
  y += 40;
  doc.font('Helvetica').fontSize(7.5).fillColor(C.muted).text(`${t.legend}  ·  ${t.na}`, M, y, { width: CW });
  y += 13;
  const colW = (CW - 16) / 2;
  const cols = [CHECKLIST.slice(0, 3), CHECKLIST.slice(3)];
  const RH = 13.6, HH = 17;
  let bottom = y;
  cols.forEach((cats, ci) => {
    const x0 = M + ci * (colW + 16);
    let cy = y;
    for (const cat of cats) {
      doc.roundedRect(x0, cy, colW, HH, 4).fill(C.navy2);
      doc.font('Helvetica-Bold').fontSize(8).fillColor('#FFFFFF').text(cat[lang] || cat.en, x0 + 8, cy + 5, { width: colW - 76, height: 10, lineBreak: false, ellipsis: true });
      ['S', 'I', 'C'].forEach((l, k) => doc.text(l, x0 + colW - 62 + k * 20, cy + 5, { width: 14, align: 'center', lineBreak: false }));
      cy += HH;
      cat.items.forEach((it, idx) => {
        if (idx % 2 === 1) doc.rect(x0, cy, colW, RH).fill('#FAFBFD');
        const r = card.ratings[it.key];
        doc.font(r ? 'Helvetica-Bold' : 'Helvetica').fontSize(8.5).fillColor(r ? C.ink : C.ink2)
          .text(it[lang] || it.en, x0 + 8, cy + 3.2, { width: colW - 80, height: 10, lineBreak: false, ellipsis: true });
        ['S', 'I', 'C'].forEach((l, k) => {
          const cx = x0 + colW - 55 + k * 20, cyy = cy + RH / 2;
          if (r === l) {
            const col = l === 'S' ? C.s : l === 'I' ? C.i : C.c;
            doc.circle(cx, cyy, 5.8).fill(col);
            doc.font('Helvetica-Bold').fontSize(7.5).fillColor('#FFFFFF').text(l, cx - 6, cyy - 2.8, { width: 12, align: 'center', lineBreak: false });
          } else {
            doc.circle(cx, cyy, 5.8).lineWidth(0.6).stroke(C.line);
            doc.font('Helvetica').fontSize(7).fillColor('#B5C0CF').text(l, cx - 6, cyy - 2.6, { width: 12, align: 'center', lineBreak: false });
          }
        });
        doc.moveTo(x0, cy + RH).lineTo(x0 + colW, cy + RH).lineWidth(0.4).stroke(C.line);
        cy += RH;
      });
      cy += 6;
    }
    bottom = Math.max(bottom, cy);
  });

  // ---- text sections
  y = bottom + 4;
  const section = (title, body, accent = C.navy) => {
    const text = body && String(body).trim() ? String(body) : '—';
    doc.font('Helvetica').fontSize(9.5);
    const h = doc.heightOfString(text, { width: CW - 24 }) + 30;
    if (y + h > doc.page.height - 56) { doc.addPage(); y = 40; }
    doc.roundedRect(M, y, CW, h, 8).lineWidth(0.8).stroke(C.line);
    doc.rect(M, y + 8, 3, h - 16).fill(accent);
    doc.font('Helvetica-Bold').fontSize(8).fillColor(C.muted).text(title.toUpperCase(), M + 12, y + 9, { characterSpacing: 0.4 });
    doc.font('Helvetica').fontSize(9.5).fillColor(C.ink).text(text, M + 12, y + 21, { width: CW - 24 });
    y += h + 8;
  };
  // Summary and "what was done" side by side to keep the card on one page.
  {
    const half = (CW - 12) / 2;
    const val = (v) => (v && String(v).trim() ? String(v) : '—');
    doc.font('Helvetica').fontSize(9);
    const h = Math.max(doc.heightOfString(val(card.intervention_summary), { width: half - 24 }), doc.heightOfString(val(card.what_was_done), { width: half - 24 })) + 28;
    if (y + h > doc.page.height - 56) { doc.addPage(); y = 40; }
    [[t.summary, card.intervention_summary], [t.done, card.what_was_done]].forEach(([title, body], k) => {
      const x = M + k * (half + 12);
      doc.roundedRect(x, y, half, h, 8).lineWidth(0.8).stroke(C.line);
      doc.rect(x, y + 8, 3, h - 16).fill(C.orange);
      doc.font('Helvetica-Bold').fontSize(7.5).fillColor(C.muted).text(title.toUpperCase(), x + 12, y + 9, { characterSpacing: 0.4, width: half - 24 });
      doc.font('Helvetica').fontSize(9).fillColor(C.ink).text(val(body), x + 12, y + 20, { width: half - 24 });
    });
    y += h + 8;
  }

  if (card.status === 'closed') {
    const comment = card.review_comment && card.review_comment.trim() ? card.review_comment : '—';
    doc.font('Helvetica').fontSize(9.5);
    const h = doc.heightOfString(comment, { width: CW - 24 }) + 52;
    if (y + h > doc.page.height - 56) { doc.addPage(); y = 40; }
    doc.roundedRect(M, y, CW, h, 8).fill(C.cBg);
    doc.font('Helvetica-Bold').fontSize(8).fillColor(C.c).text(t.review.toUpperCase(), M + 12, y + 10, { characterSpacing: 0.4 });
    doc.font('Helvetica').fontSize(8.5).fillColor(C.ink2)
      .text(`${t.closed_by}: `, M + 12, y + 24, { continued: true }).font('Helvetica-Bold').fillColor(C.ink).text(card.reviewer_name || '—', { continued: true })
      .font('Helvetica').fillColor(C.ink2).text(`     ${t.closed_on}: `, { continued: true }).font('Helvetica-Bold').fillColor(C.ink).text(fmtDate(card.reviewed_at, lang, 'long'));
    doc.font('Helvetica').fontSize(9.5).fillColor(C.ink).text(comment, M + 12, y + 40, { width: CW - 24 });
    y += h + 8;
  }

  // ---- footer on every page
  const range = doc.bufferedPageRange();
  const stamp = new Date().toLocaleString(lang === 'es' ? 'es-US' : 'en-US', { dateStyle: 'medium', timeStyle: 'short' });
  for (let p = range.start; p < range.start + range.count; p++) {
    doc.switchToPage(p);
    doc.page.margins.bottom = 0; // footer sits inside the bottom margin; don't let it spawn a new page
    const fy = doc.page.height - 30;
    doc.moveTo(M, fy - 6).lineTo(W - M, fy - 6).lineWidth(0.5).stroke(C.line);
    doc.font('Helvetica').fontSize(7.5).fillColor(C.muted)
      .text(`${t.generated} · ${stamp}`, M, fy, { width: CW / 2, lineBreak: false })
      .text(`${t.page} ${p + 1}/${range.count}`, M + CW / 2, fy, { width: CW / 2, align: 'right', lineBreak: false });
  }
  doc.end();
  return done;
}
